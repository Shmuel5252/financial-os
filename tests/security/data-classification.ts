// Phase 18 rows 18-07/18-20 (repository portion): field-level classification of every governed collection, plus the backup stores,
// TTL indexes and hard-delete paths that exist TODAY. Descriptive only: nothing here is a retention policy or an Owner decision
// (see PHASE_18_RETENTION_DRAFT.md, DRAFT / NOT ADOPTED). CI (tests/unit/data-classification.test.ts) fails when a collection,
// a top-level field, a manual-section field, a TTL index or a hard-delete call site appears without a classification here.
//
// Vocabulary
// - class: what the value is. `pseudonymous-identifier` = a keyed (HMAC) or unkeyed (sha256) transform of an identifier; it is
//   still personal data (anyone holding the key, or the input for unkeyed hashes, can link it). Nothing here is "anonymous".
// - personal: direct (identifies a person by itself), indirect (about an identifiable user, e.g. via userId), pseudonymous
//   (identifier transformed by hash/HMAC; re-linkable), none.
// - transform: raw (stored as received/produced), sha256 (unkeyed hash), hmac (keyed hash), truncated (shortened/masked text),
//   derived (computed from other data).
// - role: canonical-financial (user-owned source records) vs derived-financial (snapshots, reports, indexes, AI output) vs
//   provider-observation vs identity-and-access vs user-preference vs operational-metadata vs deletion-evidence vs offline-migration.
// - fieldSource: `type` = top-level fields must equal the TypeScript document type(s) of `.collection<T>(...)`; `manual-section`
//   = ManualRecordDocument + the section's zod domain schema for `fields.*`; `auth-adapter` = written by @auth/mongodb-adapter
//   (field list from the cited library source; any app-side typed view must be a subset).
// Field rows were produced by three independent read-only source traces (2026-10-01) and checked against the type checker.

export type FieldClass = "record-id" | "owner-id" | "reference-id" | "direct-identifier" | "pseudonymous-identifier" | "secret"
  | "secret-verifier" | "content-digest" | "financial-value" | "financial-text" | "financial-attribute" | "derived-financial"
  | "audit-trail" | "operational";
export type Personal = "direct" | "indirect" | "pseudonymous" | "none";
export type Transform = "raw" | "sha256" | "hmac" | "truncated" | "derived";
export type Role = "canonical-financial" | "derived-financial" | "provider-observation" | "identity-and-access" | "user-preference"
  | "operational-metadata" | "deletion-evidence" | "offline-migration";
